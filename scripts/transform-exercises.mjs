// Build-time generator (run once, output committed).
//
//   Reads:  data/exercises.json  (ExerciseDB OSS, 1,324 rows — github.com/hasaneyldrm/exercises-dataset)
//   Writes: supabase/migrations/20260708000100_exercise_dataset_seed.sql
//
// Emits ONE `INSERT ... ON CONFLICT (slug) DO NOTHING` so the 18 curated rows
// from 0032 always win. This file is a build artifact — only its .sql output
// is required by `supabase db push`.
//
//   Usage: node scripts/transform-exercises.mjs <path/to/exercises.json>
//
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, '..');
const SRC = process.argv[2] ?? resolve(REPO, '.claude/tmp/exercises.json');
const OUT = resolve(REPO, 'supabase/migrations/20260708000100_exercise_dataset_seed.sql');

const COMPOUND_EQUIP = new Set(['barbell', 'smith machine', 'leverage machine']);

// slugify + de-dupe (repeated dataset names get -2, -3, …)
const seen = new Set();
function slugify(name) {
  const base = String(name)
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '') // strip accents
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  let s = base || 'exercise';
  let i = 2;
  while (seen.has(s)) s = `${base}-${i++}`;
  seen.add(s);
  return s;
}

const snake = (v) =>
  String(v ?? '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');

const uniq = (a) => [...new Set(a.filter(Boolean))];

// upper-arms byTarget disambiguation
function byTarget(target) {
  const t = String(target ?? '').toLowerCase();
  if (t.includes('bicep')) return 'Bis';
  if (t.includes('tricep')) return 'Tris';
  return 'Upper Arms';
}

function bodyPart(rec) {
  const bp = String(rec.body_part ?? '').toLowerCase();
  switch (bp) {
    case 'chest': return 'Chest';
    case 'back': return 'Back';
    case 'shoulders': return 'Shoulders';
    case 'upper legs': return 'Legs';
    case 'lower legs': return 'Legs';
    case 'waist': return 'Abs';
    case 'cardio': return 'Cardio';
    case 'upper arms': return byTarget(rec.target);
    case 'lower arms': return 'Lower Arms';
    case 'neck': return 'Neck';
    default:
      // widened CHECK admits Title Case fall-through so nothing aborts
      return bp.replace(/\b\w/g, (c) => c.toUpperCase());
  }
}

function category(rec) {
  if (String(rec.body_part ?? '').toLowerCase() === 'cardio') return 'cardio';
  const sec = Array.isArray(rec.secondary_muscles) ? rec.secondary_muscles : [];
  const equip = String(rec.equipment ?? '').toLowerCase();
  if (sec.length >= 2 || COMPOUND_EQUIP.has(equip)) return 'compound';
  return 'isolation';
}

// SQL literal escaping (single quotes doubled). null → NULL.
const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const jarr = (a) => `'${JSON.stringify(a).replace(/'/g, "''")}'`; // jsonb array literal
const jobj = (o) => (o == null ? 'NULL' : `'${JSON.stringify(o).replace(/'/g, "''")}'`);

const raw = JSON.parse(readFileSync(SRC, 'utf8'));
const arr = Array.isArray(raw) ? raw : raw.exercises ?? raw.data ?? [];
if (!Array.isArray(arr) || arr.length === 0) {
  throw new Error(`No records found in ${SRC}`);
}

const unmapped = {};
const bpCounts = {};
const rows = [];

for (const rec of arr) {
  const slug = slugify(rec.name);
  const bp = bodyPart(rec);
  const cat = category(rec);
  const prim = uniq([snake(rec.target), snake(rec.muscle_group)]);
  const sec = uniq((Array.isArray(rec.secondary_muscles) ? rec.secondary_muscles : []).map(snake));
  const equip = rec.equipment ? [snake(rec.equipment)] : [];
  const instr = rec.instructions ?? null;

  bpCounts[bp] = (bpCounts[bp] || 0) + 1;
  const KNOWN = new Set(['Push','Pull','Legs','Abs','Chest','Back','Bis','Tris','Shoulders','Cardio','Mobility','Full Body']);
  if (!KNOWN.has(bp)) unmapped[bp] = (unmapped[bp] || 0) + 1;

  // Column order (matches INSERT below):
  // slug,name,aliases,category,primary_muscles,secondary_muscles,equipment,
  // body_part,description,cues,common_mistakes,instructions,media_id,target,source
  rows.push(
    '  (' +
      [
        q(slug),
        q(rec.name),
        `'[]'`,
        q(cat),
        jarr(prim),
        jarr(sec),
        jarr(equip),
        q(bp),
        'NULL',
        `'[]'`,
        `'[]'`,
        jobj(instr),
        q(rec.media_id ?? null),
        q(rec.target ?? null),
        `'exercisedb_oss'`,
      ].join(',') +
      ')'
  );
}

const header = `-- ============================================================
-- Seed: open-source exercise dataset (ExerciseDB OSS, ${rows.length} rows).
-- GENERATED by scripts/transform-exercises.mjs — do not hand-edit.
-- Additive: ON CONFLICT (slug) DO NOTHING → the 18 curated rows from 0032 win.
-- Depends on 20260708000000_exercise_dataset_columns.sql (additive columns).
-- ============================================================

INSERT INTO public.exercises
  (slug, name, aliases, category, primary_muscles, secondary_muscles, equipment,
   body_part, description, cues, common_mistakes, instructions, media_id, target, source)
VALUES
${rows.join(',\n')}
ON CONFLICT (slug) DO NOTHING;
`;

writeFileSync(OUT, header, 'utf8');

// ---- report ----
console.log(`rows emitted: ${rows.length}`);
console.log(`output: ${OUT}`);
console.log('body_part distribution:', JSON.stringify(bpCounts, null, 0));
console.log('unmapped (widened-CHECK) labels:', JSON.stringify(unmapped));
